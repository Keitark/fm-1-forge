import { build } from 'esbuild';
import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { appearanceRuntime } from '../lib/fm1-appearance.mjs';
import { forgeProjectRuntime } from '../lib/fm1-forge-project.mjs';
import { moduleGraphRuntime } from '../lib/fm1-module-graph.mjs';
import { extensionRuntime } from '../lib/fm1-extension-ui.mjs';
import { inventoryRuntime } from '../lib/fm1-inventory-refresh.mjs';
import { libraryRuntime } from '../lib/fm1-library-ui.mjs';
import { inputRuntime } from '../lib/fm1-input-ui.mjs';

const root=new URL('../',import.meta.url);
const built=await build({entryPoints:[fileURLToPath(new URL('lib/fm1-app-host.mjs',root))],
  bundle:true,write:false,format:'iife',platform:'browser',target:'es2022',minify:true,legalComments:'inline'});
const sdk=JSON.parse(await readFile(new URL('node_modules/@modelcontextprotocol/ext-apps/package.json',root),'utf8'));
const extensions=JSON.parse(await readFile(new URL('node_modules/@openai/mcp-extensions/package.json',root),'utf8'));
const code=built.outputFiles[0].text.replaceAll('</script','<\\/script');
// Freeze serialized browser functions before the server compiler renames their
// identifiers. Function.toString() on a minified server can lose dependencies.
const runtimes={appearanceRuntime,forgeProjectRuntime,moduleGraphRuntime,extensionRuntime,inventoryRuntime,libraryRuntime,inputRuntime};
await writeFile(new URL('lib/fm1-app-sdk.generated.mjs',root),
  '// Generated by scripts/build-fm1-panel.mjs from the pinned official MCP Apps and OpenAI MCP Extensions SDKs.\n'+
  'export const MCP_APPS_SDK_VERSION='+JSON.stringify(sdk.version)+';\n'+
  'export const OPENAI_MCP_EXTENSIONS_SDK_VERSION='+JSON.stringify(extensions.version)+';\n'+
  'export const MCP_APPS_SCRIPT='+JSON.stringify(code)+';\n'+
  Object.entries(runtimes).map(([name,runtime])=>'export const '+name+'='+JSON.stringify(runtime.replaceAll('</script','<\\/script'))+';').join('\n')+'\n');
console.log('FM1 panel bundled with MCP Apps SDK '+sdk.version+' and OpenAI MCP Extensions SDK '+extensions.version);
